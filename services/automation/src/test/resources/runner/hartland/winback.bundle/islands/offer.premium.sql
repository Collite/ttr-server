SELECT "sk", "hdemo", "orders_before", "income_band", "top_band", "route", 'lapsed for ' || CAST(:quiet_months AS VARCHAR) || ' months, a top income band' AS "verdict_reason"
FROM (SELECT "t22"."sk", "t22"."hdemo", "t22"."orders_before", "t36"."income_band", "t36"."top_band", CASE WHEN "t36"."top_band" = 1 THEN 'premium' ELSE 'standard' END AS "route"
        FROM (SELECT "t7"."sk", "t7"."hdemo", "t7"."orders_before"
                FROM (SELECT "t6"."customer" AS "sk", "customer"."hdemo", "t6"."orders_before"
                        FROM (SELECT "t1"."customer", "t1"."orders_before"
                                FROM (SELECT "customer", COUNT("order_number") AS "orders_before"
                                        FROM "order"
                                        WHERE "placed_date" >= :as_of_minus_quiet_months_months_minus_12_months AND "placed_date" <= :as_of_minus_quiet_months_months
                                        GROUP BY "customer"
                                        HAVING COUNT("order_number") >= :active_orders) AS "t1"
                                    LEFT JOIN (SELECT "customer", 1 AS "_ttrp_exists"
                                        FROM "order"
                                        WHERE "placed_date" >= :as_of_minus_quiet_months_months AND "placed_date" <= :as_of
                                        GROUP BY "customer") AS "t4" ON "t1"."customer" = "t4"."customer"
                                WHERE "t4"."_ttrp_exists" IS NULL) AS "t6"
                            INNER JOIN "customer" ON "t6"."customer" = "customer"."sk") AS "t7"
                    LEFT JOIN (SELECT "sk", 1 AS "_ttrp_exists"
                        FROM (SELECT "t16"."sk", "t16"."hdemo", "t16"."orders_before", "winback_mail"."quarter", "winback_mail"."offer", "winback_mail"."run", "winback_mail"."mailed_at"
                                FROM (SELECT "t15"."customer" AS "sk", "customer0"."hdemo", "t15"."orders_before"
                                        FROM (SELECT "t10"."customer", "t10"."orders_before"
                                                FROM (SELECT "customer", COUNT("order_number") AS "orders_before"
                                                        FROM "order"
                                                        WHERE "placed_date" >= :as_of_minus_quiet_months_months_minus_12_months AND "placed_date" <= :as_of_minus_quiet_months_months
                                                        GROUP BY "customer"
                                                        HAVING COUNT("order_number") >= :active_orders) AS "t10"
                                                    LEFT JOIN (SELECT "customer", 1 AS "_ttrp_exists"
                                                        FROM "order"
                                                        WHERE "placed_date" >= :as_of_minus_quiet_months_months AND "placed_date" <= :as_of
                                                        GROUP BY "customer") AS "t13" ON "t10"."customer" = "t13"."customer"
                                                WHERE "t13"."_ttrp_exists" IS NULL) AS "t15"
                                            INNER JOIN "customer" AS "customer0" ON "t15"."customer" = "customer0"."sk") AS "t16"
                                    INNER JOIN "winback_mail" ON "t16"."sk" = "winback_mail"."customer") AS "t17"
                        WHERE "t17"."mailed_at" >= :as_of_minus_mail_window_days
                        GROUP BY "sk") AS "t20" ON "t7"."sk" = "t20"."sk"
                WHERE "t20"."_ttrp_exists" IS NULL) AS "t22"
            LEFT JOIN (SELECT "t33"."sk", "t33"."income_band", CASE WHEN "t35"."band_id" IS NOT NULL THEN 1 ELSE 0 END AS "top_band"
                FROM (SELECT "t31"."sk", "t31"."hdemo", "t31"."orders_before", "t32"."income_band"
                        FROM (SELECT "t30"."customer" AS "sk", "customer1"."hdemo", "t30"."orders_before"
                                FROM (SELECT "t25"."customer", "t25"."orders_before"
                                        FROM (SELECT "customer", COUNT("order_number") AS "orders_before"
                                                FROM "order"
                                                WHERE "placed_date" >= :as_of_minus_quiet_months_months_minus_12_months AND "placed_date" <= :as_of_minus_quiet_months_months
                                                GROUP BY "customer"
                                                HAVING COUNT("order_number") >= :active_orders) AS "t25"
                                            LEFT JOIN (SELECT "customer", 1 AS "_ttrp_exists"
                                                FROM "order"
                                                WHERE "placed_date" >= :as_of_minus_quiet_months_months AND "placed_date" <= :as_of
                                                GROUP BY "customer") AS "t28" ON "t25"."customer" = "t28"."customer"
                                        WHERE "t28"."_ttrp_exists" IS NULL) AS "t30"
                                    INNER JOIN "customer" AS "customer1" ON "t30"."customer" = "customer1"."sk") AS "t31"
                            LEFT JOIN (SELECT "sk" AS "household_id", "income_band"
                                FROM "household_demographics") AS "t32" ON "t31"."hdemo" = "t32"."household_id") AS "t33"
                    LEFT JOIN (SELECT "sk" AS "band_id", - "lower_bound" AS "priority"
                        FROM "income_band"
                        ORDER BY - "lower_bound"
                        FETCH NEXT 2 ROWS ONLY) AS "t35" ON "t33"."income_band" = "t35"."band_id") AS "t36" ON "t22"."sk" = "t36"."sk") AS "t37"
WHERE "t37"."route" = 'premium'
